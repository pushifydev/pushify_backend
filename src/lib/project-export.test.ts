import { describe, it, expect } from 'vitest';
import {
  buildProjectExport,
  resolveImportedEnvVars,
  ProjectExportBundleSchema,
  PROJECT_EXPORT_FORMAT,
  type BuildProjectExportInput,
} from './project-export';

const project: BuildProjectExportInput['project'] = {
  name: 'Shop',
  description: null,
  gitRepoUrl: 'https://github.com/acme/shop',
  gitBranch: 'main',
  stagingBranch: null,
  gitProvider: 'github',
  installCommand: 'npm ci',
  buildCommand: 'npm run build',
  startCommand: 'npm start',
  outputDirectory: null,
  rootDirectory: '/',
  dockerfilePath: null,
  dockerImage: null,
  composePath: 'docker-compose.yml',
  composeService: 'web',
  composePort: 8080,
  composePullPolicy: 'missing',
  port: 3000,
  autoDeploy: true,
  replicas: 2,
  autoscaleEnabled: false,
  autoscaleMin: 1,
  autoscaleMax: 3,
  autoscaleObserveOnly: false,
  sleepEnabled: false,
  sleepAfterMinutes: 30,
};

function input(overrides: Partial<BuildProjectExportInput> = {}): BuildProjectExportInput {
  return {
    project,
    envVars: [
      { key: 'NODE_ENV', environment: 'production', isSecret: false, locked: false, value: 'production' },
      { key: 'STRIPE_KEY', environment: 'production', isSecret: true, locked: false, value: 'sk_live_123' },
      { key: 'ADMIN_TOKEN', environment: 'staging', isSecret: false, locked: true, value: null },
    ],
    domains: [
      { domain: 'shop.example.com', isPrimary: true, isAutoGenerated: false, environment: 'production', nginxSettings: {} },
      { domain: 'shop-x1.pushify.app', isPrimary: false, isAutoGenerated: true, environment: 'production', nginxSettings: null },
    ],
    scheduledTasks: [
      { name: 'cleanup', type: 'command', schedule: '0 3 * * *', timezone: 'UTC', command: 'npm run cleanup', httpUrl: null, timeoutSeconds: 300, enabled: true },
    ],
    workers: [{ name: 'queue', command: 'npm run worker', enabled: true }],
    volumes: [{ name: 'uploads', containerPath: '/app/uploads' }],
    databases: [{ id: 'db-1', name: 'shop-db', type: 'postgresql', envVarName: 'DATABASE_URL' }],
    apiUrl: 'https://api.example.com',
    now: new Date('2026-11-13T00:00:00Z'),
    ...overrides,
  };
}

describe('buildProjectExport', () => {
  it('leaves secret values out by default and keeps plain ones', () => {
    const bundle = buildProjectExport(input());

    expect(ProjectExportBundleSchema.parse(bundle)).toEqual(bundle);
    expect(bundle.format).toBe(PROJECT_EXPORT_FORMAT);
    expect(bundle.secrets).toEqual({ mode: 'excluded' });
    expect(bundle.envVars).toEqual([
      { key: 'NODE_ENV', environment: 'production', isSecret: false, locked: false, value: 'production' },
      { key: 'STRIPE_KEY', environment: 'production', isSecret: true, locked: false, value: null },
      { key: 'ADMIN_TOKEN', environment: 'staging', isSecret: false, locked: true, value: null },
    ]);
    expect(JSON.stringify(bundle)).not.toContain('sk_live_123');
  });

  it('drops the auto-generated subdomain and points linked databases at backup/import', () => {
    const bundle = buildProjectExport(input());

    expect(bundle.domains).toEqual([
      { domain: 'shop.example.com', isPrimary: true, environment: 'production', nginxSettings: {} },
    ]);
    expect(bundle.databases[0]).toMatchObject({ name: 'shop-db', type: 'postgresql', envVarName: 'DATABASE_URL' });
    expect(bundle.databases[0].dataMigration).toContain('/api/v1/databases/db-1/backups');
    expect(bundle.project.composePath).toBe('docker-compose.yml');
    expect(bundle.volumes).toEqual([{ name: 'uploads', containerPath: '/app/uploads' }]);
  });

  it('encrypts secrets with a passphrase; the same passphrase restores them', () => {
    const bundle = buildProjectExport(input({ passphrase: 'correct horse battery' }));

    expect(bundle.secrets.mode).toBe('encrypted');
    expect(JSON.stringify(bundle)).not.toContain('sk_live_123');
    const secret = bundle.envVars.find((v) => v.key === 'STRIPE_KEY')!;
    expect(secret.value).toBeNull();
    expect(secret.valueEncrypted).toBeTruthy();

    const { variables, skipped } = resolveImportedEnvVars(bundle, 'correct horse battery');
    expect(variables.map((v) => [v.key, v.value])).toEqual([
      ['NODE_ENV', 'production'],
      ['STRIPE_KEY', 'sk_live_123'],
    ]);
    expect(skipped).toEqual([
      { key: 'ADMIN_TOKEN', environment: 'staging', reason: 'Value not included in the export' },
    ]);
  });
});

describe('resolveImportedEnvVars', () => {
  it('refuses a wrong passphrase instead of importing part of the variables', () => {
    const bundle = buildProjectExport(input({ passphrase: 'correct horse battery' }));
    expect(() => resolveImportedEnvVars(bundle, 'wrong passphrase!!')).toThrow(/passphrase does not match/);
  });

  it('skips encrypted secrets when no passphrase is given', () => {
    const bundle = buildProjectExport(input({ passphrase: 'correct horse battery' }));
    const { variables, skipped } = resolveImportedEnvVars(bundle);

    expect(variables.map((v) => v.key)).toEqual(['NODE_ENV']);
    expect(skipped.map((s) => [s.key, s.reason])).toEqual([
      ['STRIPE_KEY', 'Encrypted; no passphrase given'],
      ['ADMIN_TOKEN', 'Value not included in the export'],
    ]);
  });

  it('rejects a bundle of another format', () => {
    const bundle = buildProjectExport(input());
    expect(ProjectExportBundleSchema.safeParse({ ...bundle, format: 'pushify.project/v0' }).success).toBe(false);
  });
});
